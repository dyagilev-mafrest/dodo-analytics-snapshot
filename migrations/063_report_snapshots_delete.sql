-- Право удалять выпущенный отчёт.
--
-- Изначально таблица его не имела сознательно: замороженный снапшот — запись о
-- том, что видели на встрече, и на него ссылаются задачи. Исчезающий отчёт
-- ломает подотчётность, ради которой он и заведён.
--
-- Но выхода из случайного выпуска не было вовсе. Перегенерация (upsert) чинит
-- только снапшот, выпущенный за ВЕРНЫЙ период по неверным данным; снапшот,
-- выпущенный не за тот период, оставался в архиве навсегда.
--
-- Поэтому право даётся, но узко: в интерфейсе удаление живёт внутри открытого
-- снапшота и в два шага, а не строкой в списке — чтобы человек сначала увидел,
-- что именно удаляет. Массового удаления не предусмотрено.

DROP POLICY IF EXISTS authenticated_delete ON report_snapshots;
CREATE POLICY authenticated_delete ON report_snapshots
  FOR DELETE TO authenticated USING (true);

GRANT DELETE ON report_snapshots TO authenticated;
