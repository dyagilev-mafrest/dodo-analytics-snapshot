-- Пересборка hr_hiring_funnel: датировка по отчётной неделе и недостающие поля.
--
-- ЧТО БЫЛО НЕ ТАК (найдено 16.09.2026)
--
-- 1. Неделя записывалась по метке блока листа, а блок заполняется на встрече в
--    начале недели N и отчитывается за неделю N-1 (заголовок так и говорит:
--    «План ПРЕДЫДУЩЕЙ недели»). Доказательство: блок «14.09-20.09» уже содержал
--    факт 13 и уволено 16, хотя неделя кончается 20-го, а читали лист 16-го.
--    Все факты в таблице были сдвинуты на неделю вперёд.
--
-- 2. Колонки листа читались со смещением на одну: «План на следующую неделю»
--    брался из колонки G вместо H, вся мини-таблица воронки — на одну левее, а
--    «назначенные пробные смены» (колонка M) не запрашивались вовсе — выборка
--    шла до L. Отсюда NULL в plan_next у 37 недель из 38 и пустая воронка во
--    всех 38.
--
-- 3. В 38-й неделе в листе появилась колонка «Уволено», которой в таблице не
--    было. Без неё найм читается без обратного потока: за 37-ю неделю кухня
--    наняла 13 и потеряла 16.
--
-- ЧТО ИЗМЕНИЛОСЬ В СХЕМЕ
--
-- `*_plan_prev` переименованы в `*_hiring_plan`: после сдвига это план ровно той
-- недели, под которой лежит строка. `*_plan_next` удалены как избыточные —
-- «план на следующую неделю» из блока N это и есть план недели N, он ложится
-- своей строкой, а следующий блок его же подтверждает колонкой «план
-- предыдущей». Текущая неделя поэтому существует строкой с планом и пустым
-- фактом — ровно так её и рассказывают на встрече.
--
-- ⚠️ НЕ СВОДИТСЯ С team_metrics_kitchen_monthly. Сумма недельных фактов за
-- август — 67 по кухне против 21 в месячных метриках HR, за июнь 102 против 32.
-- Сдвиг этого не объясняет: разрыв втрое при любой датировке. Похоже, в недельном
-- листе «принятыми» считают раньше по воронке, чем оформление в Dodo IS. Вопрос
-- задан HR 16.09.2026, до ответа две цифры рядом на одном экране показывать нельзя.
ALTER TABLE hr_hiring_funnel RENAME COLUMN kitchen_plan_prev TO kitchen_hiring_plan;
ALTER TABLE hr_hiring_funnel RENAME COLUMN courier_plan_prev TO courier_hiring_plan;

ALTER TABLE hr_hiring_funnel DROP COLUMN IF EXISTS kitchen_plan_next;
ALTER TABLE hr_hiring_funnel DROP COLUMN IF EXISTS courier_plan_next;

ALTER TABLE hr_hiring_funnel ADD COLUMN IF NOT EXISTS kitchen_dismissed integer;
ALTER TABLE hr_hiring_funnel ADD COLUMN IF NOT EXISTS courier_dismissed integer;

-- Строки прежней датировки бессмысленны: у них неделя сдвинута, а воронки нет
