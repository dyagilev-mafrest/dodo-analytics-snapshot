-- ingredient_stop_impact: одна строка на (стоп, продукт, ДЕНЬ) вместо одной на
-- (стоп, продукт).
--
-- ЗАЧЕМ. Построчная выгрузка Dodo IS `Stop_Ingredients_detailed_table`
-- (09.09.2026) показала, как эталон относит деньги многодневного стопа: НЕ к
-- периоду начала и НЕ пропорционально времени, а пересчётом каждого периода от
-- его собственной базы. Пример — «Сыр Блю Чиз», Якутск-5, стоп начался 10.07 и
-- не закрыт:
--
--   неделя 13.07 → 54 842,88 ₽
--   неделя 20.07 → 33 785,76 ₽
--   неделя 27.07 → 10 598,88 ₽
--   неделя 03.08 и далее → 0,00 ₽
--
-- Цифра ЗАТУХАЕТ: база — три предыдущих одинаковых дня недели, и чем дольше
-- позиция стоит, тем больше этих дней сами стоповые. Через три недели
-- непрерывного стопа потерянных продаж не остаётся — спрос ушёл.
--
-- Одним числом на стоп такую форму не выразить: дашборд относил всю сумму к
-- бакету начала (сходимость 117 %) или размазывал её пропорционально времени
-- (189 %, деньги затягивались в окно из стопов, начавшихся до него). А
-- `compute_for_stop` и так считает по дням со своей базой на каждый день —
-- достаточно перестать схлопывать результат.
--
-- ПОЧЕМУ ПО ДНЯМ, А НЕ ПО НЕДЕЛЯМ. Дашборд бакетит по дню, неделе и месяцу
-- (фильтр «Бизнес-пульс» свободный). Дневная гранулярность — единственная, из
-- которой собираются все три; недельная закрыла бы дневной шаг.
--
-- Таблица полностью производная (пересчитывается из stop_events, product_recipe
-- и product_daily_revenue), поэтому старые строки просто удаляются: они
-- восстанавливаются прогоном compute_ingredient_stop_impact.py.

DELETE FROM ingredient_stop_impact;

ALTER TABLE ingredient_stop_impact
    ADD COLUMN IF NOT EXISTS stop_date date;

-- Значение обязательно: строка без дня снова превратит таблицу в «одно число на
-- стоп», и атрибуция молча поедет.
UPDATE ingredient_stop_impact SET stop_date = CURRENT_DATE WHERE stop_date IS NULL;
ALTER TABLE ingredient_stop_impact ALTER COLUMN stop_date SET NOT NULL;

ALTER TABLE ingredient_stop_impact DROP CONSTRAINT IF EXISTS ingredient_stop_impact_pkey;
ALTER TABLE ingredient_stop_impact
    ADD CONSTRAINT ingredient_stop_impact_pkey
    PRIMARY KEY (stop_event_id, product_uuid, stop_date);

-- Дашборд читает метрику за период, поэтому основной доступ — по дню.
CREATE INDEX IF NOT EXISTS ingredient_stop_impact_date
    ON ingredient_stop_impact (stop_date);

COMMENT ON COLUMN ingredient_stop_impact.stop_date IS
    'Календарный день, за который посчитана упущенная выручка. Многодневный стоп даёт по строке на день; сумма за день считается от базы этого дня, поэтому по мере затягивания стопа она затухает.';
