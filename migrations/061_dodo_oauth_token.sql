-- Единственное место хранения OAuth-токена Dodo IS.
--
-- Зачем: refresh_token у Dodo IS одноразовый — он проворачивается при каждом
-- рефреше, а прежний становится недействительным. Пока пара лежала в секретах
-- GitHub, писателей было двое (CI и локальная машина), и каждый мог сжечь токен
-- другому. За два месяца это дало пять разных механизмов отказа, последний —
-- 12-13.09.2026, когда легли все 13 загрузчиков. Плюс задание в GitHub Actions
-- получает значения секретов, снятые на СТАРТЕ прогона: обновление, сделанное
-- внутри того же прогона, до соседних джоб не доезжает в принципе.
--
-- В БД обе проблемы исчезают: строка одна, читается в момент обращения (а не на
-- старте прогона), и пишется под блокировкой — см. token_store.py.

CREATE TABLE IF NOT EXISTS dodo_oauth_token (
    provider      text PRIMARY KEY,
    access_token  text NOT NULL,
    refresh_token text NOT NULL,
    -- Когда протухает access_token. Загрузчик рефрешит сам, если срок близко,
    -- поэтому цепочка переживает падение стража, а не ждёт его.
    expires_at    timestamptz NOT NULL,
    updated_at    timestamptz NOT NULL DEFAULT now(),
    -- Кто обновил: 'token_guard', имя загрузчика, 'local'. Нужно при разборе
    -- расхождений — по нему видно, чей рефреш был последним.
    updated_by    text
);

-- ⚠️ Здесь ровно наоборот, чем у обычных таблиц дашборда (тем нужны политики и
-- для anon, и для authenticated): токен не должен быть виден НИКОМУ из клиентских
-- ролей. ETL ходит прямым подключением под SUPABASE_USER, а он RLS обходит.
ALTER TABLE dodo_oauth_token ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON dodo_oauth_token FROM anon, authenticated;
