-- Минуты стопа В РАБОЧИЕ ЧАСЫ доставки — то, что показывает Dodo IS в колонках
-- «Время стопов … в рабочие часы» дашборда «Стопы пиццерий и активность секторов
-- доставки». Заполняет compute_stop_lost_revenue.py тем же обходом по часам, каким
-- считает упущенную выручку (hour_segments обрезает стоп рабочим окном).
--
-- Зачем отдельная колонка: duration_minutes — сырая длительность стопа, и фронт
-- суммировал её. На сверке 02.09.2026 по секторам это давало завышение до +25%
-- (5381 минута против 4288 у Dodo IS за неделю 03–09.08), тогда как обрезанные
-- минуты сходятся с Dodo IS почти в ноль. См. docs/unit-sector-stops-methodology.md.
--
-- NULL значит «не считали»: стопы вне диапазонов пересчёта, ещё не закрытые стопы и
-- строки, не участвующие в метрике (Dine-in/Takeaway, Redirection, удалённые секторы).
-- Потребитель должен падать на duration_minutes, если тут NULL.
ALTER TABLE stop_events ADD COLUMN IF NOT EXISTS working_minutes numeric;
